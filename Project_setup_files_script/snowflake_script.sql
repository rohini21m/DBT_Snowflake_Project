-- 5. INITIAL BASELINE LOAD (run only AFTER uploading the CSVs)
COPY INTO COMPANY_INFO.RAW.EMPLOYEES
    FROM @COMPANY_INFO.RAW.STG_EMPLOYEES
    FILE_FORMAT = (FORMAT_NAME = FF_EMPLOYEE_CSV)
    FILES = ('employees_us.csv', 'employees_de.csv', 'employees_in.csv')
    ON_ERROR = ABORT_STATEMENT;

COPY INTO COMPANY_INFO.RAW.DEPARTMENTS
    FROM @COMPANY_INFO.RAW.STG_EMPLOYEES
    FILE_FORMAT = (FORMAT_NAME = FF_EMPLOYEE_CSV)
    FILES = ('departments.csv')
    ON_ERROR = ABORT_STATEMENT;

COPY INTO COMPANY_INFO.RAW.LEAVE_EVENTS
    FROM @COMPANY_INFO.RAW.STG_EMPLOYEES
    FILE_FORMAT = (FORMAT_NAME = FF_EMPLOYEE_CSV)
    FILES = ('leave_initial.csv')
    ON_ERROR = ABORT_STATEMENT;

-- Expected clean baseline: 30 employees, 9 departments, 90 leave events.
SELECT 'EMPLOYEES' AS SOURCE_TABLE, COUNT(*) AS ROW_COUNT FROM COMPANY_INFO.RAW.EMPLOYEES
UNION ALL
SELECT 'DEPARTMENTS', COUNT(*) FROM COMPANY_INFO.RAW.DEPARTMENTS
UNION ALL
SELECT 'LEAVE_EVENTS', COUNT(*) FROM COMPANY_INFO.RAW.LEAVE_EVENTS;
