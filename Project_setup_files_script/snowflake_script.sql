-- 2. SHARED CSV FORMAT
CREATE OR REPLACE FILE FORMAT COMPANY_INFO.RAW.FF_EMPLOYEE_CSV
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_DELIMITER = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('', 'NULL')
    DATE_FORMAT = 'YYYY-MM-DD'
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- 3. INTERNAL STAGES + SOURCE TABLES
CREATE STAGE IF NOT EXISTS COMPANY_INFO.RAW.STG_EMPLOYEES
    FILE_FORMAT = FF_EMPLOYEE_CSV;


CREATE TABLE IF NOT EXISTS COMPANY_INFO.RAW.EMPLOYEES (
    EMPLOYEE_ID VARCHAR(20),
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    WORK_EMAIL VARCHAR(255),
    COUNTRY_CODE VARCHAR(2),
    DEPARTMENT_ID VARCHAR(30),
    HIRE_DATE DATE,
    EMPLOYMENT_STATUS VARCHAR(20),
    SOURCE_UPDATED_AT DATE
);

CREATE TABLE IF NOT EXISTS COMPANY_INFO.RAW.DEPARTMENTS (
    DEPARTMENT_ID VARCHAR(30),
    COUNTRY_CODE VARCHAR(2),
    LOCAL_DEPARTMENT_NAME VARCHAR(100),
    EFFECTIVE_FROM DATE
);

CREATE TABLE IF NOT EXISTS COMPANY_INFO.RAW.LEAVE_EVENTS (
    LEAVE_ID VARCHAR(20),
    EMPLOYEE_ID VARCHAR(20),
    COUNTRY_CODE VARCHAR(2),
    SOURCE_LEAVE_CODE VARCHAR(40),
    LEAVE_DATE DATE,
    DAYS_TAKEN NUMBER(10,0),
    SOURCE_UPDATED_AT DATE
);

